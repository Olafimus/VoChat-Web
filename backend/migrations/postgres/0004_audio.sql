-- Aussprache-Aufnahmen (z. B. Wikimedia Commons / Lingua Libre, freie Lizenzen). Gespeichert wird
-- nur der Verweis samt Lizenz und Sprecher; die Datei selbst liegt beim Anbieter.
CREATE TABLE lexeme_audio (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lexeme_id INTEGER NOT NULL REFERENCES lexemes(id) ON DELETE CASCADE,
  url TEXT NOT NULL,
  source TEXT NOT NULL,
  license TEXT,
  speaker TEXT,
  region TEXT,
  created_at BIGINT NOT NULL,
  UNIQUE (lexeme_id, url)
);
CREATE INDEX lexeme_audio_lexeme ON lexeme_audio (lexeme_id);

-- Lautschrift (IPA), getrennt von der Umschrift (romanization).
ALTER TABLE lexemes ADD COLUMN ipa TEXT;
